test('suggested strategic areas require explicit creation, can reuse exact names, and save separately (mock AI)', async ({ users }) => {
  test.setTimeout(60000)
  const [alice] = await users(1)
  const page = alice.page
  const prefix = `__suggested-${Date.now()}__`
  const name = `${prefix} Quant Math`
  await page.route('**/api/ai/**', (route) => route.fulfill({ status: 200, json: { proposal: {
    title: 'Quant Math Foundations', context: 'Build fluency in quantitative reasoning and clear explanations.', existingPrepAreaIds: [],
    suggestedPrepAreas: [{ name }],
  } } }))
  await page.goto('/plans/prep/new')
  await page.getByLabel('Preparation goal', { exact: true }).fill('Improve quant math')
  await page.getByRole('button', { name: 'Build my prep plan', exact: true }).click()
  const suggestions = page.getByRole('region', { name: 'Suggested Prep Areas' })
  await expect(suggestions).toBeVisible()
  await expect(page.getByRole('checkbox', { name, exact: true })).toHaveCount(0)
  await suggestions.getByRole('button', { name: 'Add Prep Area', exact: true }).click()
  await expect(page.getByLabel('Area name', { exact: true })).toHaveValue(name)
  await page.getByLabel('Area name', { exact: true }).fill(`${name} edited`)
  await expect(page.getByRole('checkbox', { name: `${name} edited`, exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Create Prep Area', exact: true }).click()
  const checkbox = page.getByRole('checkbox', { name: `${name} edited`, exact: true })
  await expect(checkbox).toBeChecked()
  const areaId = await checkbox.getAttribute('value')
  expect(areaId).toBeTruthy()
  await expect(page).toHaveURL(/\/plans\/prep\/new$/)
  await expect(page.getByRole('button', { name: 'Save prep plan', exact: true })).toBeVisible()
  await expect(suggestions).toHaveCount(0)
  // Regeneration does not remove the explicitly created area, or save the plan.
  await page.getByRole('button', { name: 'Regenerate strategy', exact: true }).click()
  await expect(suggestions).toBeVisible()
  await expect(checkbox).toBeVisible()
  await suggestions.getByRole('button', { name: 'Add Prep Area', exact: true }).click()
  await page.getByLabel('Area name', { exact: true }).fill(`  ${name.toUpperCase()} EDITED  `)
  await expect(page.getByRole('button', { name: 'Use existing area', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Use existing area', exact: true }).click()
  await expect(checkbox).toBeChecked()
  await expect(checkbox).toHaveAttribute('value', areaId!)
  const request = page.waitForRequest('**/api/actions/createPrepPlan')
  await page.getByRole('button', { name: 'Save prep plan', exact: true }).click()
  expect((await request).postDataJSON()).toMatchObject({ prepAreaIds: [areaId], goal: 'Improve quant math' })
  expect((await request).postDataJSON()).not.toHaveProperty('suggestedPrepAreas')
  await expect(page).toHaveURL(/\/plans\/prep\/(?!new$)/)
  await page.reload()
  await expect(page.getByText(`${name} edited`, { exact: true })).toBeVisible()
})
