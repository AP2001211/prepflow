import { describe, expect, it } from 'vitest'
import { CONTEXT_LIMITS, prepReader } from './prep-context'
import { buildTools } from './tools'
import { contextFixture, existingProposal } from './planner-test-fixture'

const now = Date.parse('2026-10-02T12:00:00Z')
describe('Bounded caller-scoped planner reads', () => {
  it('exposes exactly two read tools and scopes all reads to the executor identity', async () => {
    const f = contextFixture()
    expect(Object.keys(buildTools(f.executor))).toEqual(['get_prep_snapshot', 'get_work_context'])
    const snapshot = await prepReader(f.executor).snapshot({}, now)
    expect(snapshot.prepAreas.map((row) => row.id)).toEqual(['area'])
    expect(snapshot.openWork.map((row) => row.id)).toEqual(['item'])
    expect(snapshot.openWork[0]?.previouslyStarted).toBe(false)
    expect(snapshot.openWork[0]?.planMemberships).toHaveLength(2)
    expect(snapshot.openPlans.map((row) => row.id)).toEqual(['later'])
    await expect(prepReader(f.executor).workContext('foreign-item')).rejects.toThrow('unavailable')
    await expect(prepReader(f.executor).snapshot({ prepAreaIds: ['foreign-area'] })).rejects.toThrow('unavailable')
    expect(f.executor.mock.calls.every(([name]) => name === 'records.get' || name === 'records.query')).toBe(true)
  })
  it('caps records, text and recent history, explicitly describing partial coverage', async () => {
    const f = contextFixture()
    for (let i = 0; i < 40; i++) f.add('prep-areas', `area-${i}`, { name: `Area ${i}`, notes: 'x'.repeat(1000) })
    for (let i = 0; i < 40; i++) f.add('prep-sessions', `session-${i}`, { planItemId: 'item', prepAreaId: 'area', startedAt: '2026-10-01T12:00:00Z', endedAt: '2026-10-01T12:10:00Z', state: 'ended', outcome: 'switched', encounteredStuck: true, notes: 'y'.repeat(10000) })
    const snapshot = await prepReader(f.executor).snapshot({}, now)
    expect(snapshot.prepAreas).toHaveLength(CONTEXT_LIMITS.areas)
    expect(snapshot.coverage.areas.truncated).toBe(true)
    expect(snapshot.prepAreas.every((row) => (row.notesPreview?.length ?? 0) <= CONTEXT_LIMITS.previewChars)).toBe(true)
    expect(snapshot.recentFocus).toHaveLength(CONTEXT_LIMITS.recentIntervals)
    expect(snapshot.recentFocus[0]).toMatchObject({ focusMinutes: 10, encounteredDifficulty: true, outcome: 'switched' })
    expect(snapshot.recentFocus[0]).not.toHaveProperty('notes')
    expect(snapshot.coverageNotices.join(' ')).toContain('not lifetime history')
    const detail = await prepReader(f.executor).workContext('item')
    expect(detail.recentIntervals).toHaveLength(5)
    expect(detail.recentIntervals[0]?.notes).toHaveLength(CONTEXT_LIMITS.detailChars)
    expect(detail.coverage.truncated).toBe(true)
    expect(detail.behavioralObservations).toMatchObject({ observedAttemptCount: 5, observedSwitchedCount: 5, observedDifficultyAndSwitchedCount: 5, observedFocusMinutes: 50 })
    expect(detail.observationCoverage).toMatchObject({ truncated: true, lifetime: false })
  })
  it('selects the latest ended interval before looking for context; never falls back', async () => {
    const f = contextFixture()
    const base = { planItemId: 'item', prepAreaId: 'area', startedAt: '2026-10-01T12:00:00Z', state: 'ended', outcome: 'switched', encounteredStuck: false }
    f.add('prep-sessions', 'older', { ...base, endedAt: '2026-10-01T12:10:00Z', leftOff: 'Stale blocker', nextStep: 'Stale next' })
    f.add('prep-sessions', 'latest', { ...base, endedAt: '2026-10-01T13:10:00Z' })
    const snapshot = await prepReader(f.executor).snapshot({}, now)
    expect(snapshot.openWork[0]).toMatchObject({ previouslyStarted: true, latestResumeContext: { sessionId: 'latest', leftOff: null, nextStep: null } })
    expect((await prepReader(f.executor).workContext('item')).latestResumeContext).toMatchObject({ sessionId: 'latest', leftOff: null, nextStep: null })
    const latest = f.tables.get('prep-sessions')?.find((row) => row.recordId === 'latest')
    if (!latest) throw new Error('Missing fixture')
    latest.data.leftOff = 'Current blocker'
    expect((await prepReader(f.executor).snapshot({}, now)).openWork[0]?.latestResumeContext?.leftOff).toBe('Current blocker')
  })
  it('reports current focus, recent completed work and upcoming optional interviews', async () => {
    const f = contextFixture()
    f.add('prep-sessions', 'active', { planItemId: 'item', intent: 'Window functions', state: 'active', startedAt: '2026-10-02T11:00:00Z' })
    f.add('plan-items', 'done', { prepAreaId: 'area', intent: 'Joins', status: 'completed', completedAt: '2026-10-01T13:00:00Z' })
    f.add('interviews', 'future', { company: 'Example', scheduledDate: '2026-10-07', prepAreaIds: ['area'] })
    f.add('interviews', 'past', { company: 'Past', scheduledDate: '2026-09-01', prepAreaIds: ['area'] })
    const snapshot = await prepReader(f.executor).snapshot({}, now)
    expect(snapshot.openWork[0]?.currentlyFocused).toBe(true)
    expect(snapshot.currentFocus).toHaveLength(1)
    expect(snapshot.recentlyCompleted.map((row) => row.id)).toEqual(['done'])
    expect(snapshot.interviews.map((row) => row.id)).toEqual(['future'])
    expect((await prepReader(f.executor).snapshot({ interviewId: 'past' }, now)).interviews).toHaveLength(2)
  })
  it('enriches canonical names and rejects fabricated/foreign references and completed/pending work', async () => {
    const f = contextFixture(); const reader = prepReader(f.executor)
    expect(await reader.enrich(existingProposal)).toEqual([{ intent: 'Window functions', prepAreaId: 'area', prepAreaName: 'SQL', previouslyStarted: false }])
    for (const id of ['missing', 'foreign-item']) await expect(reader.enrich({ ...existingProposal, items: [{ ...existingProposal.items[0], existingPlanItemId: id }] })).rejects.toThrow('unavailable')
    await expect(reader.enrich({ ...existingProposal, items: [{ kind: 'new', intent: 'Forged', prepAreaId: 'foreign-area', estimatedMinutes: 30, reason: 'Invalid' }] })).rejects.toThrow('unavailable')
    await expect(reader.enrich({ ...existingProposal, items: [{ kind: 'new', intent: 'Forged', prepAreaId: 'area', interviewId: 'missing', estimatedMinutes: 30, reason: 'Invalid' }] })).rejects.toThrow('unavailable')
    f.add('prep-sessions', 'pending', { planItemId: 'item', state: 'ended', outcome: 'completed', endedAt: '2026-10-02T11:00:00Z' })
    await expect(reader.enrich(existingProposal)).rejects.toThrow('reconciliation')
    const item = f.tables.get('plan-items')?.find((row) => row.recordId === 'item')
    if (!item) throw new Error('Missing fixture')
    item.data.status = 'completed'
    await expect(reader.enrich(existingProposal)).rejects.toThrow('no longer open')
  })
})

it('computes factual bounded observations without counting active or older history', async () => {
  const f = contextFixture()
  const base = { planItemId: 'item', prepAreaId: 'area', intent: 'Window functions', startedAt: '2026-10-01T12:00:00Z', endedAt: '2026-10-01T12:10:00Z', state: 'ended', encounteredStuck: false }
  f.add('prep-sessions', 'a', { ...base, outcome: 'completed' })
  f.add('prep-sessions', 'b', { ...base, outcome: 'stopped', encounteredStuck: true })
  f.add('prep-sessions', 'c', { ...base, outcome: 'switched', encounteredStuck: true })
  f.add('prep-sessions', 'old', { ...base, startedAt: '2020-01-01T12:00:00Z', endedAt: '2020-01-01T12:10:00Z', outcome: 'stopped' })
  f.add('prep-sessions', 'active', { ...base, state: 'active', endedAt: undefined })
  const snapshot = await prepReader(f.executor).snapshot({}, now)
  expect(snapshot.openWork[0]?.behavioralObservations).toEqual({ observedAttemptCount: 3, observedCompletedCount: 1, observedStoppedCount: 1, observedSwitchedCount: 1, observedDifficultyCount: 2, observedDifficultyAndSwitchedCount: 1, observedFocusMinutes: 30, latestObservedAttemptAt: base.startedAt })
  expect(snapshot.openWork[0]?.observationCoverage).toMatchObject({ lifetime: false, limit: 30, truncated: false, until: new Date(now).toISOString() })
  const detail = await prepReader(f.executor).workContext('item')
  expect(detail.behavioralObservations.observedAttemptCount).toBe(4)
  expect(detail.observationCoverage).toMatchObject({ lifetime: false, limit: 5, since: null })
})
it('bounds instruction previews and enriches existing instructions canonically', async () => {
  const f = contextFixture()
  const item = f.tables.get('plan-items')!.find((row) => row.recordId === 'item')!
  item.data.instructions = 'x'.repeat(2000)
  const reader = prepReader(f.executor)
  expect((await reader.snapshot({}, now)).openWork[0]?.instructions).toHaveLength(300)
  expect((await reader.workContext('item')).instructions).toHaveLength(2000)
  expect((await reader.enrich(existingProposal))[0]?.instructions).toBe(item.data.instructions)
  expect(f.executor.mock.calls.every(([name]) => name === 'records.get' || name === 'records.query')).toBe(true)
})

it('separates historical memberships from local-day unresolved daily context', async () => {
  const f = contextFixture()
  f.add('plan-items', 'done', { prepAreaId: 'area', intent: 'Done', status: 'completed' })
  f.add('plans', 'past-daily', { title: 'Past', planDate: '2026-10-01', planItemIds: ['item'] })
  f.add('plans', 'completed-daily', { title: 'Completed today', planDate: '2026-10-02', planItemIds: ['done'] })
  f.add('plans', 'current-daily', { title: 'Current', planDate: '2026-10-02', planItemIds: ['item'] })
  f.add('plans', 'missing-daily', { title: 'Unresolved', planDate: '2026-10-02', planItemIds: ['missing'] })
  const reader = prepReader(f.executor, 'America/Los_Angeles')
  const snapshot = await reader.snapshot({}, Date.parse('2026-10-03T02:00:00Z'))
  expect(snapshot.openPlans.map((p) => p.id)).toEqual(expect.arrayContaining(['later', 'current-daily', 'missing-daily']))
  expect(snapshot.openPlans.map((p) => p.id)).not.toEqual(expect.arrayContaining(['past-daily']))
  expect(snapshot.openPlans.map((p) => p.id)).not.toEqual(expect.arrayContaining(['completed-daily']))
  expect(snapshot.openWork[0]?.planMemberships.map((p) => p.id)).toContain('past-daily')
})

it('keeps evidence at actual now while selecting target plans and interview deadlines', async () => {
  const f = contextFixture()
  f.add('plans', 'target', { title: 'Future', planDate: '2026-10-07', planItemIds: ['item'] })
  f.add('plans', 'today-plan', { title: 'Today', planDate: '2026-10-02', planItemIds: ['item'] })
  f.add('interviews', 'before-target', { company: 'Before', scheduledDate: '2026-10-06', prepAreaIds: [] })
  f.add('interviews', 'on-target', { company: 'On', scheduledDate: '2026-10-07', prepAreaIds: [] })
  const snapshot = await prepReader(f.executor, 'UTC', '2026-10-07').snapshot({}, now)
  expect(snapshot.asOf).toBe('2026-10-02T12:00:00.000Z')
  expect(snapshot.evidenceLocalDate).toBe('2026-10-02')
  expect(snapshot.targetPlanDate).toBe('2026-10-07')
  expect(snapshot.openPlans.map((p) => p.id)).toContain('target')
  expect(snapshot.openPlans.map((p) => p.id)).not.toContain('today-plan')
  expect(snapshot.interviews.map((p) => p.id)).not.toContain('before-target')
  expect(snapshot.interviews.find((p) => p.id === 'on-target')?.timingRelativeToPlanDate).toBe('on')
  expect(snapshot.coverage.recentIntervals.until).toBe(snapshot.asOf)
})

describe('canonical automatic availability', () => {
  it.each(['2026-10-05', '2026-10-06', '2026-10-07', '2026-10-08'])('uses target %s independently of evidence time', async (target) => {
    const f = contextFixture()
    f.add('plan-items', 'future', { prepAreaId: 'area', intent: 'Future work', status: 'open', availableFrom: '2026-10-07' })
    f.add('plans', 'future-plan', { title: 'Future', planDate: '2026-10-07', planItemIds: ['item', 'future'] })
    f.add('prep-sessions', 'attempt', { planItemId: 'item', state: 'ended', outcome: 'stopped', startedAt: '2026-10-01T12:00:00Z', endedAt: '2026-10-01T12:10:00Z', leftOff: 'Existing context' })
    const reader = prepReader(f.executor, 'UTC', target)
    const snapshot = await reader.snapshot({}, now)
    expect(snapshot.asOf).toBe('2026-10-02T12:00:00.000Z')
    expect(snapshot.openWork.some((item) => item.id === 'future')).toBe(target >= '2026-10-07')
    expect(snapshot.openWork.find((item) => item.id === 'item')).toMatchObject({ previouslyStarted: true, latestResumeContext: { leftOff: 'Existing context' } })
    if (target < '2026-10-07') {
      await expect(reader.workContext('future')).rejects.toThrow('deferred')
      await expect(reader.enrich({ ...existingProposal, items: [{ ...existingProposal.items[0]!, existingPlanItemId: 'future' }] })).rejects.toThrow('deferred')
    } else {
      expect((await reader.workContext('future')).availableFrom).toBe('2026-10-07')
      expect(await reader.enrich({ ...existingProposal, items: [{ ...existingProposal.items[0]!, existingPlanItemId: 'future' }] })).toHaveLength(1)
    }
  })
})
